/**
 * Localiza a aba disciplinar pelo `id` ou por qualquer `alias` legado (ex: `'humanas'` → `'filosofia_sociologia'`).
 */
export function resolveStudySubjectTab(tabIdOrAlias) {
  if (!tabIdOrAlias) return STUDY_SUBJECT_TABS[0];
  const normalized = String(tabIdOrAlias).trim().toLowerCase();
  return (
    STUDY_SUBJECT_TABS.find(
      t =>
        t.id === normalized ||
        (Array.isArray(t.aliases) && t.aliases.includes(normalized))
    ) || STUDY_SUBJECT_TABS[0]
  );
}
